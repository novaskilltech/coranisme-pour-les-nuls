// Injection dans les fichiers JS de traduction
Object.keys(LANDING_TRANSLATIONS).forEach(code => {
  const filePath = path.join(TRANSLATIONS_DIR, `${code}.js`);
  if (!fs.existsSync(filePath)) return;

  let content = fs.readFileSync(filePath, 'utf8');
  const strings = LANDING_TRANSLATIONS[code];

  // Inserer chaque clé dans "ui": { ... } ou ui: { ... }
  const formattedEntries = Object.keys(strings).map(key => {
    return `    "${key}": "${strings[key].replace(/\\/g, '\\\\').replace(/"/g, '\\"')}",`;
  }).join('\n');

  if (content.includes('"ui": {')) {
    content = content.replace('"ui": {', `"ui": {\n${formattedEntries}`);
  } else if (content.includes('ui: {')) {
    content = content.replace('ui: {', `ui: {\n${formattedEntries}`);
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`[OK] Traductions Landing Page injectées pour : ${code}`);
});

